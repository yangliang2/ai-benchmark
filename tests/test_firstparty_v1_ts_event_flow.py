"""Round 7's second TypeScript planted defect (#106): one subscription that
listens for the first of something that happens all evening, authored as two
tasks that share it.

`lockhouse-work-the-rest-of-the-night-through` asks for the fix and
`lockhouse-locate-the-boats-that-never-reached-the-book` asks only for the
location, over one hand-authored asynchronous event flow holding one planted
defect: `Keeper.keep` registers the boat coming up the cut with `once` where
it must be `on`. The first boat of the night is taken, worked through and
written up exactly as it should be; every boat behind it is given out by the
cut to a listener that is no longer there, so it is never taken, never turned
back and never written up. Nothing throws, nothing is left half done, and the
night settles as it always did — what is wrong with the page is only what is
not on it. Same terrain, same defect, two actions, which is what makes "what
does locating cost, as against fixing?" a reading of the two actions rather
than of two repositories.

This is `tests/test_firstparty_v1_ts_http_service.py`'s suite over the second
TypeScript scenario, and it proves the same things over terrain that is
asynchronous rather than a service. What it checks that no other suite can:

- **The two members really do share one repository**, byte for byte. Those
  shared bytes are how the lint finds the `bug-fix` partner that is the locate
  member's registered existence proof; the lint reads them for *finding* the
  partner rather than for holding the two trees identical, so this is still
  the only thing that says they have not drifted.
- **The defect the fix removes is the defect the key names.** The lint proves
  the answer key discriminates and the reference solution proves the fix
  works, but nothing joins them: here the file the fix touches and the file
  every accepted answer names are asserted to be one file.
- **No verdict on either side is decided by wall-clock timing.** This is the
  rule the ticket sets and the spec does not: an asynchronous defect graded by
  sleeping and then looking is a verdict about the scheduler on the grading
  machine, and round 1 already paid for one of those. Every observable here is
  a settled promise or a recorded sequence — the night's promise settles when
  the cut has shut *and* the queue has run out, and the page is a list in the
  order it was written. Asserted from both sides: no test on either side of
  the verdict names a timer or a clock, and every held-out test reads its
  verdict off the night's own promise.
- **The repository is what ADR-0003 says a TypeScript task ships**: flat, no
  manifest and no installed tree, `node:` builtins and relative `.ts` imports
  only, and an entry point guarded the way Node 22 allows, so that every
  module is side-effect-free at import.
- **The scenario is a real asynchronous event flow**, which is the reason this
  task exists rather than an eighth Python one, and it is disclosed in the
  prompt rather than as a task field.
- **The repository reproduces the symptom nowhere the agent can see it.** The
  visible suite exercises many boats at the level *below* the night — the
  tally counts three that came up, the page is headed off the first of three,
  the lock takes two one behind another — and never sends a second boat up one
  night. Proved by making any second boat an outright error and watching the
  suite stay green, with the vacuous reading refused first by pointing the
  subscription at an event nothing gives out and watching it go red.
- **What the key accepts and refuses on this task's own terrain**: both
  description levels the author wrote down resolve, and every other symbol of
  the defective file does not.
- **The terrain leaves the locating to be done**, the half the task-set lint
  cannot see: `.once(` and `.on(` are a shape a grep finds in one pass, so the
  repository holds seven more registrations across all four modules and every
  one of them is correct; two of the three events are registered *both* ways
  somewhere and each way is right where it stands, so the shape decides
  nothing at all; and the contract the defect breaks is written a file's
  length from the line that breaks it.
- **What no pattern can tell apart**, which is this defect's whole
  discrimination: `Book.headed` listens for the first of the very same event
  and is correct, because a page is headed once. Asserted by running the two
  over one night two boats came up on, under the Node that grades them.
- **The two repairs that are not the fix**: the same edit made to the twin,
  and a repair that takes every boat but hands the night back before the work
  is done. Both graded through the real pipeline rather than argued about.
- **The hash gate**, generated by the CLI flag and never typed, holding the
  locate member to answering rather than repairing.

The rest is what every checked-in task has to prove — lints clean, reference
solution grades resolved, the empty diff grades unresolved — all through the
same execution-verified pipeline real runs go through.
"""


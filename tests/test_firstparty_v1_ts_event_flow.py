def test_a_repair_that_does_not_wait_for_the_work_is_not_the_fix() -> None:
    """The other near-miss, and the one this scenario exists to be able to
    refuse.

    Taking every boat is half the night; the other half is that the promise the
    lockhouse hands back settles when the work is *done*. A repair that
    subscribes correctly and then lets each boat go off on its own hands back a
    page that is still being written, and the held-out tests read the page off
    that promise — so the half-repair grades unresolved, and no test had to
    guess how long to wait to say so.
    """
    fix = task_by_id(BUG_FIX)

    def let_go(workdir: Path) -> None:
        swapping(DEFECTIVE_LINE, f"{FIXED_LINE}\n")(workdir)
        swapping(
            "    this.working = this.working.then(() => this.workThrough(boat));",
            "    void this.workThrough(boat);",
        )(workdir)

    [record] = evaluate(
        [fix], [run_for(fix, workdir_diff(fix, let_go))], source="run-log"
    )
    assert record.quality_value == 0.0



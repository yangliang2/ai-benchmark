def test_the_contract_is_not_written_on_top_of_the_defect() -> None:
    """Honest, and not in one glance.

    Whether a boat that came up behind another may be dropped is the whole of
    the inference, so a comment saying so three lines above the line that drops
    it removes the last step of the work. It is stated once, in the module
    comment at the top of the file, and the defect is well down it: a reader has
    to carry it there. The defective method's own comment says what the method
    hands back and is silent about which boats reach it.
    """
    lines = repo_source(DEFECTIVE_FILE).splitlines()
    defect = next(at for at, line in enumerate(lines) if line == DEFECTIVE_LINE.rstrip())
    comment = " ".join(" ".join(lines[: lines.index(" */")]).replace("*", " ").split())

    assert " ".join(CONTRACT.split()) in comment
    assert not any(
        word in line
        for line in lines[max(0, defect - 12):defect]
        for word in (
            "what comes up the cut queues", "lost nothing by it",
            "the queue is empty", "in the sequence it arrived",
        )
    )
    assert defect > 30
    assert "  async keep(): Promise<string[]> {" in lines[defect - 1 : defect]



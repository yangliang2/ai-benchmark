def test_no_visible_test_sends_a_second_boat_up_one_night() -> None:
    """*Why* the visible suite is green, asserted rather than hoped for.

    A subscription hung on the first of something is invisible to every test
    that never produces a second one, and the repository is written so that
    nothing visible ever sends two boats up one night. It exercises many boats
    one level down instead — the tally counts three that came up, the page is
    headed off the first of three, the lock takes two one behind another —
    which legitimises the shape in the repository's own voice without
    reproducing the symptom. That is a property of the fixtures rather than of
    the code, and it would be silently lost the first time a visible test put
    two boats up one evening.

    Asserted by making a second boat an outright error: if the suite stays
    green with the subscription taking every boat and throwing on the second,
    nothing visible reaches it.

    The vacuous reading is refused first: with the subscription pointed at an
    event nothing gives out, the suite has to go red, or nothing visible sends
    a boat up at all and the reading above is about nothing.
    """
    locate = task_by_id(FAULT_LOCATION)

    assert not visible_tests_pass(
        locate, edit=swapping(DEFECTIVE_LINE, '    this.cut.once("nothing at all", (boat: Boat) => {\n')
    )
    assert visible_tests_pass(
        locate,
        edit=swapping(
            DEFECTIVE_LINE,
            "    let first = true;\n"
            "    this.cut.on(A_BOAT, (boat: Boat) => {\n"
            "      if (!first) {\n"
            '        throw new Error("a second boat reached the lockhouse");\n'
            "      }\n"
            "      first = false;\n",
        ),
    )



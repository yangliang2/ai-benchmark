# --- no verdict is a fact about the scheduler ----------------------------------


def test_no_test_on_either_side_of_the_verdict_waits_on_a_length_of_time() -> None:
    """The rule this ticket sets, and the reason for it.

    An asynchronous defect can always be graded the lazy way: send the boats
    up, wait a moment, look at the page. That verdict is a fact about how
    loaded the grading machine was — a sleep long enough today is short enough
    on a slower box, and round 1 already paid for a gate that turned on
    scheduler luck. So neither suite names a timer or a clock at all, and what
    the repository itself uses where the water has to arrive later is
    `queueMicrotask`: ordering, which is decided by the program, rather than
    duration, which is decided by the machine.
    """
    for source in (held_out_source(), visible_source()):
        for reached_for in WALL_CLOCK:
            assert reached_for not in source, reached_for
    assert "queueMicrotask" in repo_source("water.ts")
    for reached_for in WALL_CLOCK:
        assert reached_for not in "".join(
            path.read_text(encoding="utf-8") for path in code_files()
        ), reached_for


def test_every_held_out_verdict_is_read_off_the_night_s_own_promise() -> None:
    """The other half of the same rule, stated positively: every held-out test
    waits on the promise the night hands back, which settles when the cut has
    shut *and* the queue has run out. A test that read the page without waiting
    on that would be asserting about a moment nobody defined."""
    source = held_out_source()
    cases = source.split("\ntest(")[1:]

    assert len(cases) >= 5
    for case in cases:
        assert THE_NIGHTS_PROMISE in case, case.splitlines()[0]
    assert "keeper.keep()" in source



# --- no verdict is a fact about what was already listening ---------------------


def test_no_test_on_either_side_of_the_verdict_binds_a_port() -> None:
    """The rule this ticket sets, and the reason for it.

    A held-out test that asked the service on a port named in a file would
    grade every run unresolved on any machine where something else was already
    listening there — a verdict about the grading box rather than about the
    agent. So both suites put the service on port 0, read back the port the
    machine handed out, and interpolate that into every URL they ask on.
    """
    for source in (held_out_source(), visible_source()):
        assert "serve(desk, 0)" in source
        assert "server.address()" in source
        assert "A_PORT" not in source
        asked = _ASKED_ON.findall(source)
        assert asked
        for url in asked:
            assert "${port}" in url, url


# --- the symptom is visible and its cause is not -------------------------------


def test_the_repository_reproduces_the_symptom_in_no_visible_test() -> None:
    """The convention this corpus holds to: a failing test in the starting
    repository would point straight at the defect and delete the action both
    members measure. So the repository's own suite is green while the defect is
    in it — the symptom reaches the agent through the prompt alone."""
    for task_id in MEMBERS:
        assert visible_tests_pass(task_by_id(task_id))


def test_the_visible_suite_stays_green_on_the_fix() -> None:
    """The other direction: the fix is a fix and not a rewrite — everything the
    repository already asserted about itself still holds."""
    fix = task_by_id(BUG_FIX)

    assert visible_tests_pass(fix, edit=solved_tree(fix))


def test_no_visible_test_asks_what_is_owed_on_a_bag_nobody_weighed() -> None:
    """*Why* the visible suite is green, asserted rather than hoped for.

    A fallback is invisible to every test that never makes the guarded call
    refuse, and the repository is written so that nothing visible ever asks
    what is owed on a bag nobody wrote a weight down for. It exercises such a
    bag one level down instead — `Tariff.forStay` refuses it, `Shelf.weighed`
    hands back not weighed and `writtenUp` writes it up as unweighed — which
    legitimises the shape in the repository's own voice without reproducing the
    symptom. That is a property of the fixtures rather than of the code, and it
    would be silently lost the first time a visible test asked the counter
    about a bag off the morning the scales were out.

    Asserted by making the fallback refuse outright: if the suite stays green
    with it turned into an error, nothing visible reaches it.

    The vacuous reading is refused first: with the guarded call made to refuse
    every time, the suite has to go red, or nothing visible calls the defective
    method at all and the refusal above is about nothing.
    """
    locate = task_by_id(FAULT_LOCATION)

    assert not visible_tests_pass(
        locate, edit=swapping(GUARDED_CALL, "this.tariff.forStay(undefined)")
    )
    assert visible_tests_pass(
        locate,
        edit=swapping(
            DEFECTIVE_LINE,
            f"    const owed = {GUARDED_CALL};\n"
            "    if (owed === CANNOT_SAY) {\n"
            '      throw new Error("the fallback was reached");\n'
            "    }\n"
            "    return owed;\n",
        ),
    )


def test_each_prompt_states_the_symptom_and_not_its_cause() -> None:
    """Both members do the same detective work; only the deliverable differs.
    A prompt naming the defective module or method would make the
    fault-location task a transcription exercise."""
    for task_id in MEMBERS:
        prompt = task_by_id(task_id).prompt

        assert "left-luggage office" in prompt
        for giveaway in (
            DEFECTIVE_FILE, "Charges", "charges.ts", "owedOn", "Tariff", "forStay",
            "CANNOT_SAY", "NOTHING_OWED", "fallback", "null", "??",
        ):
            assert giveaway not in prompt, f"{task_id} names {giveaway}"


def test_both_prompts_state_the_intended_behaviour() -> None:
    """Parity of information about what correct *is*, not identical text.

    A fix member that is told what correct is while the locate member has to
    infer it understates the fix side of the very comparison the two members
    exist to produce. Here the symptom paragraphs are one text in both and the
    rule is stated in both: what separates them is the deliverable paragraph
    alone. Saying what correct is leaks no location.
    """
    prompts = [task_by_id(task_id).prompt for task_id in MEMBERS]
    symptom = "Something has gone wrong at the left-luggage office."

    for prompt in prompts:
        flowed = " ".join(prompt.split())
        assert "has no charge against that bag at all" in flowed, "no rule stated"
        assert "nothing whatever is put in its place" in flowed
        assert prompt.startswith(symptom)
    reported = {"\n\n".join(prompt.split("\n\n")[:3]) for prompt in prompts}
    assert len(reported) == 1, "the two members report different symptoms"


# --- the terrain leaves the locating to be done --------------------------------


def fallbacks() -> dict[tuple[str, str], int]:
    """Every `?? <constant>` the repository's modules fall back to."""
    found: dict[tuple[str, str], int] = {}
    for path in code_files():
        for constant in _FALLBACK.findall(path.read_text(encoding="utf-8")):
            key = (path.name, constant)
            found[key] = found.get(key, 0) + 1
    return found


def test_the_defect_is_not_the_only_fallback_in_the_repository() -> None:
    """A single `??` in the whole repository makes locating a grep.

    It is a shape a grep finds in one pass, so the repository writes nine more,
    across all four modules, and every one of them is correct: `Shelf.weighed`
    and `Shelf.leftBy` fall back to values that say outright there was nothing
    to be had, `writtenUp` writes a missing weight up as one, `Desk.noteOn`
    falls back to no note, `Charges.paidOn` falls back to nothing paid — a true
    statement about a bag nobody has paid on — and the rest are a request with
    no path on it, a port nobody named and two constructors given no map. Two
    of the ten are in the defective module itself, so reaching the right file
    finishes nothing.

    The other half of the same claim: six of the ten stand in for something
    that was genuinely not there rather than for an argument nobody passed, so
    the shape a reader would filter on still names six sites, and which of them
    is wrong is decided by what the fallback *means* rather than by the
    pattern.
    """
    found = fallbacks()

    assert found == FALLBACKS
    assert sum(found.values()) == 10
    assert len({file for file, _ in found}) == 4
    assert sum(count for (file, _), count in found.items() if file == DEFECTIVE_FILE) == 3
    assert STOOD_IN_FOR_NOTHING <= set(found)
    assert (DEFECTIVE_FILE, "NOTHING_OWED") in STOOD_IN_FOR_NOTHING


def test_the_repository_declares_the_shape_it_uses_correctly() -> None:
    """Why the nine correct ones are not merely nine more places to look.

    Several of them are asserted by the repository's own tests, so the shape is
    *legitimised* rather than left ambiguous: an agent reading the visible
    suite is told, in the repository's own voice, that falling back here is how
    the office says there was nothing to be had. And the visible suite says
    outright what a bag nobody weighed is worth — the tariff cannot say, the
    shelf hands back not weighed, the book writes it up as unweighed — so the
    concept is present everywhere except where it is thrown away.
    """
    suite = visible_source()

    for declared in (
        'test("a bag nobody weighed is written up as not weighed"',
        'test("a bag nobody wrote a weight down for comes back as not weighed"',
        'test("the tariff cannot say what a bag nobody weighed comes to"',
        'test("a bag left and fetched the same day costs nothing"',
        'test("a bag the office took no name for comes back as nobody"',
        'test("the day book writes up a bag nobody weighed as not weighed"',
    ):
        assert declared in suite, f"the visible suite no longer says {declared}"


def test_the_nearest_twin_is_the_same_shape_written_correctly() -> None:
    """This defect's whole discrimination, run rather than described.

    `writtenUp` and `Charges.owedOn` fall back off the same missing weight in
    the same `?? <constant>` shape. One is correct and one is the defect, and
    what separates them is only what the constant *means*: `writtenUp` falls
    back to a value saying the bag was not weighed, and `owedOn` falls back to
    a charge, which is a figure like any other. Nothing a grep or a linter sees
    tells them apart — so this is asserted by running both over one bag off the
    morning the scales were out, under the Node that grades the task.
    """
    with tempfile.TemporaryDirectory(prefix="ai-bench-twin-") as name:
        # A throwaway copy, because the checked-in `repo/` trees of swept tasks
        # are immutable and this writes a probe module into the tree.
        workdir = Path(name)
        shutil.copytree(repo_dir(), workdir, dirs_exist_ok=True)
        (workdir / "twin.ts").write_text(
            'import { Charges, Tariff } from "./charges.ts";\n'
            'import { Bag, NOT_WEIGHED, Shelf } from "./shelf.ts";\n'
            'import { writtenUp } from "./tickets.ts";\n'
            "\n"
            "const bag = new Bag(13, 4, NOT_WEIGHED);\n"
            "console.log(writtenUp(bag.ticket, bag.kilos));\n"
            "console.log(\n"
            "  String(new Charges(new Shelf([bag]), new Tariff(2, 1)).owedOn(13)),\n"
            ");\n",
            encoding="utf-8",
        )
        asked = subprocess.run(
            ["node", "twin.ts"],
            cwd=workdir,
            capture_output=True,
            text=True,
            check=True,
        ).stdout.split()

    assert asked == ["ticket", "13:", "not", "weighed", "0"]


def test_the_contract_is_not_written_on_top_of_the_defect() -> None:
    """Honest, and not in one glance.

    Whether a bag nobody weighed may come back as a charge is the whole of the
    inference, so a comment saying so three lines above the line that does it
    removes the last step of the work. It is stated once, in the module comment
    at the top of the file, and the defect is well down it: a reader has to
    carry it there. The defective method's own comment says what the method is
    for and is silent about what happens when nobody wrote a weight down.
    """
    lines = repo_source(DEFECTIVE_FILE).splitlines()
    defect = next(at for at, line in enumerate(lines) if line == DEFECTIVE_LINE.rstrip())
    comment = " ".join(" ".join(lines[: lines.index(" */")]).replace("*", " ").split())

    assert " ".join(CONTRACT.split()) in comment
    assert not any(
        word in line
        for line in lines[max(0, defect - 12):defect]
        for word in (
            "asks only for what", "nothing owed against", "made up for it",
            "the day run light",
        )
    )
    assert defect > 30
    assert "  /** What is owed on one bag. */" in lines[defect - 2 : defect]



"""Round 7's first TypeScript planted defect (#105): one fallback that turns
"the office cannot say" into "the office is owed nothing", authored as two
tasks that share it.

`leftluggage-put-the-unweighed-bag-back-on-the-scales` asks for the fix and
`leftluggage-locate-the-charge-nobody-arrived-at` asks only for the location,
over one hand-authored `node:http` service holding one planted defect:
`Charges.owedOn` ends `?? NOTHING_OWED`. `Tariff.forStay` hands back
`CANNOT_SAY` exactly as it is meant to when nobody wrote a weight down for the
bag; the fallback throws that away and hands the caller nought instead. A
refusal comes back as a figure, and as a figure indistinguishable from a bag
that came in and went out inside the hour, so the branch in `Desk.cashUp` that
exists to put such a ticket on the list to be weighed again never fires. Same
terrain, same defect, two actions — which is what makes "what does locating
cost, as against fixing?" a reading of the two actions rather than of two
repositories.

This is `tests/test_firstparty_v1_planted_defect_swallowed_exception.py`'s
suite in the second language, and it is the shape tickets 09-14 copy. What it
checks that no other suite can:

- **The two members really do share one repository**, byte for byte. Those
  shared bytes are how the lint finds the `bug-fix` partner that is the locate
  member's registered existence proof; the lint reads them for *finding* the
  partner rather than for holding the two trees identical, so this is still
  the only thing that says they have not drifted.
- **The defect the fix removes is the defect the key names.** The lint proves
  the answer key discriminates and the reference solution proves the fix
  works, but nothing joins them: here the file the fix touches and the file
  every accepted answer names are asserted to be one file.
- **The repository is what ADR-0003 says a TypeScript task ships**: flat,
  no manifest and no installed tree, `node:` builtins and relative `.ts`
  imports only, and an entry point guarded the way Node 22 allows, so that
  every module is side-effect-free at import.
- **The scenario is a real `node:http` service**, which is the reason this
  task exists rather than a seventh Python one, and it is disclosed in the
  prompt rather than as a task field.
- **No test on either side of the verdict binds a port.** The service is put
  on port 0 and asked on whatever the machine handed back, so a verdict is
  never a fact about what was already listening where the grading happened.
  This suite is where that is held: the spec does not decide it.
- **The repository reproduces the symptom nowhere the agent can see it.** The
  visible suite exercises a bag nobody weighed at the level *below* the
  fallback and never asks what is owed on one. Proved by making the fallback
  an outright refusal and watching the suite stay green, with the vacuous
  reading refused first by making the guarded call fail and watching it go
  red.
- **What the key accepts and refuses on this task's own terrain**: both
  description levels the author wrote down resolve, and every other symbol of
  the defective file does not.
- **The terrain leaves the locating to be done**, the half the task-set lint
  cannot see: `?? <constant>` is a shape a grep finds in one pass, so the
  repository holds nine more of them across all four modules and every one is
  correct; and the contract the defect breaks is written a file's length away
  from the line that breaks it.
- **What no pattern can tell apart**, which is this defect's whole
  discrimination: `writtenUp` falls back off the very same missing weight and
  is correct, because what it falls back to says the bag was not weighed
  rather than that nothing is owed on it. Asserted by running both over one
  unweighed bag, under the Node that grades them.
- **The hash gate**, generated by the CLI flag and never typed, holding the
  locate member to answering rather than repairing.

The rest is what every checked-in task has to prove — lints clean, reference
solution grades resolved, the empty diff grades unresolved — all through the
same execution-verified pipeline real runs go through.
"""


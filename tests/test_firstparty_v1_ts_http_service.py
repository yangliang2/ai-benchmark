def test_a_fix_that_only_stops_asking_for_money_is_not_the_fix() -> None:
    """The near-miss this defect invites, graded rather than assumed.

    The symptom is somebody asked for nothing, so the shortest thing that looks
    like a cure is to stop answering with a charge and stop there — nobody is
    asked for the wrong figure any more, and the list to go back over is still
    empty, so the bag is never weighed again. The prompt says outright that the
    ticket goes on that list, and the held-out tests grade the half-cure
    unresolved.
    """
    fix = task_by_id(BUG_FIX)

    def half_cured(workdir: Path) -> None:
        source = workdir / "desk.ts"
        text = source.read_text(encoding="utf-8")
        changed = text.replace(
            "        weighAgain.push(ticket);\n        continue;\n",
            "        continue;\n",
        )
        assert changed != text, "Desk.cashUp moved"
        source.write_text(changed, encoding="utf-8")

    diff = solution_diff(fix, mutate=half_cured)

    [record] = evaluate([fix], [run_for(fix, diff)], source="run-log")
    assert record.quality_value == 0.0


